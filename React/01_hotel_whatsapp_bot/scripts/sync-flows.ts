#!/usr/bin/env tsx
/**
 * Uploads WhatsApp Flow JSON definitions to Meta Graph API and writes
 * src/flows/flowIds.generated.ts with the resulting Flow IDs.
 *
 * Required env vars:
 *   WHATSAPP_FLOWS_GRAPH_ACCESS_TOKEN
 *   WHATSAPP_FLOWS_WABA_ID
 *   APP_BASE_URL
 *
 * Usage: npm run flows:sync
 */

import fs from "node:fs";
import path from "node:path";

// ── env ────────────────────────────────────────────────────────────────────────

function requireEnv(name: string): string {
  const val = process.env[name];
  if (!val) throw new Error(`Missing required env var: ${name}`);
  return val;
}

interface ScriptEnv {
  graphAccessToken: string;
  wabaId: string;
  appBaseUrl: string;
}

function getScriptEnv(): ScriptEnv {
  return {
    graphAccessToken: requireEnv("WHATSAPP_FLOWS_GRAPH_ACCESS_TOKEN"),
    wabaId: requireEnv("WHATSAPP_FLOWS_WABA_ID"),
    appBaseUrl: requireEnv("APP_BASE_URL"),
  };
}

// ── types ──────────────────────────────────────────────────────────────────────

interface FlowDefinitionFile {
  name: string;
  categories: string[];
  flow: unknown;
}

interface MetaFlowRecord {
  id: string;
  name: string;
  status: string;
}

interface MetaListResponse {
  data: MetaFlowRecord[];
}

interface MetaCreateResponse {
  id: string;
}

// ── Graph API helpers ──────────────────────────────────────────────────────────

const GRAPH_BASE = "https://graph.facebook.com/v21.0";

async function listFlows(
  wabaId: string,
  token: string,
): Promise<MetaFlowRecord[]> {
  const url = `${GRAPH_BASE}/${wabaId}/flows?fields=id,name,status&access_token=${encodeURIComponent(token)}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`List flows failed (${res.status}): ${await res.text()}`);
  }
  const body = (await res.json()) as MetaListResponse;
  return body.data;
}

async function createFlow(
  wabaId: string,
  token: string,
  name: string,
  categories: string[],
  endpointUri: string,
): Promise<string> {
  const res = await fetch(`${GRAPH_BASE}/${wabaId}/flows`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      name,
      categories,
      endpoint_uri: endpointUri,
      access_token: token,
    }),
  });
  if (!res.ok) {
    throw new Error(
      `Create flow "${name}" failed (${res.status}): ${await res.text()}`,
    );
  }
  const body = (await res.json()) as MetaCreateResponse;
  return body.id;
}

async function uploadFlowJson(
  flowId: string,
  token: string,
  flowJson: unknown,
): Promise<void> {
  const form = new FormData();
  form.append(
    "file",
    new Blob([JSON.stringify(flowJson)], { type: "application/json" }),
    "flows.json",
  );
  form.append("name", "flows.json");
  form.append("asset_type", "FLOW_JSON");
  form.append("access_token", token);

  const res = await fetch(`${GRAPH_BASE}/${flowId}/assets`, {
    method: "POST",
    body: form,
  });
  if (!res.ok) {
    throw new Error(
      `Upload JSON for flow "${flowId}" failed (${res.status}): ${await res.text()}`,
    );
  }
}

// ── file helpers ───────────────────────────────────────────────────────────────

function readDefinitions(
  dir: string,
): Array<FlowDefinitionFile & { file: string }> {
  if (!fs.existsSync(dir)) {
    throw new Error(`Definitions directory not found: ${dir}`);
  }
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".flow.json"));
  if (files.length === 0) {
    throw new Error(`No *.flow.json files found in ${dir}`);
  }
  return files.map((file) => {
    const raw = fs.readFileSync(path.join(dir, file), "utf-8");
    const parsed = JSON.parse(raw) as FlowDefinitionFile;
    if (!parsed.name || !Array.isArray(parsed.categories) || !parsed.flow) {
      throw new Error(
        `Invalid definition in "${file}": must have "name", "categories", and "flow" fields`,
      );
    }
    return { ...parsed, file };
  });
}

function nameToKey(name: string): string {
  // "hotel-date-picker" → "hotelDatePicker"
  return name.replace(/-([a-z])/g, (_, c: string) =>
    (c as string).toUpperCase(),
  );
}

function writeGeneratedIds(
  outputPath: string,
  ids: Record<string, string>,
): void {
  const entries = Object.entries(ids)
    .map(([k, v]) => `  ${k}: "${v}",`)
    .join("\n");
  const content = [
    "// AUTO-GENERATED by scripts/sync-flows.ts — do not edit manually",
    `// Last synced: ${new Date().toISOString()}`,
    "export const flowIds = {",
    entries,
    "} as const;",
    "",
    "export type FlowIdKey = keyof typeof flowIds;",
    "",
  ].join("\n");
  fs.writeFileSync(outputPath, content, "utf-8");
}

// ── main ──────────────────────────────────────────────────────────────────────

async function main(): Promise<void> {
  const env = getScriptEnv();
  const endpointUri = `${env.appBaseUrl}/api/whatsapp-flows/data-exchange`;
  const definitionsDir = path.resolve(process.cwd(), "src/flows/definitions");
  const outputPath = path.resolve(
    process.cwd(),
    "src/flows/flowIds.generated.ts",
  );

  console.log("Reading definitions from:", definitionsDir);
  const definitions = readDefinitions(definitionsDir);
  console.log(
    `Found ${definitions.length} flow(s):`,
    definitions.map((d) => d.name).join(", "),
  );

  console.log("\nFetching existing Meta flows...");
  const existing = await listFlows(env.wabaId, env.graphAccessToken);
  const existingByName = new Map(existing.map((f) => [f.name, f]));
  console.log(`Remote flows: ${existing.length}`);

  const generatedIds: Record<string, string> = {};

  for (const def of definitions) {
    const existingFlow = existingByName.get(def.name);
    let flowId: string;

    if (existingFlow) {
      console.log(
        `\n[${def.name}] already exists (id=${existingFlow.id}, status=${existingFlow.status}) — updating JSON`,
      );
      flowId = existingFlow.id;
    } else {
      console.log(`\n[${def.name}] not found — creating...`);
      flowId = await createFlow(
        env.wabaId,
        env.graphAccessToken,
        def.name,
        def.categories,
        endpointUri,
      );
      console.log(`  Created: id=${flowId}`);
    }

    console.log(`  Uploading JSON...`);
    await uploadFlowJson(flowId, env.graphAccessToken, def.flow);
    console.log(`  Upload OK`);

    generatedIds[nameToKey(def.name)] = flowId;
  }

  console.log("\nWriting:", outputPath);
  writeGeneratedIds(outputPath, generatedIds);

  console.log("\nDone. Generated IDs:");
  for (const [key, id] of Object.entries(generatedIds)) {
    console.log(`  ${key} = ${id}`);
  }
  console.log(
    "\nNote: flows are in DRAFT status — publish each one manually in WhatsApp Manager after review.",
  );
}

main().catch((err: unknown) => {
  console.error(
    "\nsync-flows failed:",
    err instanceof Error ? err.message : err,
  );
  process.exit(1);
});
